"""Regenerate checked-in responsive assets: python scripts/images/generate_variants.py.
Requires Pillow with WebP support. Originals are retained unchanged.
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2] / "frontend/biogarden-client/src"
ASSETS = ROOT / "assets/images"
NAMES = ["firstcarousel", "secondcarousel", "thirdcarousel", "fourthcarousel", "actual", "bemutatkozo", "bemutatokep"]
imports, entries = [], []
original_bytes = large_bytes = small_bytes = 0
for name in NAMES:
    source = ASSETS / f"{name}.jpg"
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original).convert("RGB")
        widths = sorted({min(768, image.width), image.width})
        candidates = []
        sizes = []
        for width in widths:
            height = max(1, round(image.height * width / image.width))
            output = ASSETS / f"{name}-{width}w.webp"
            image.resize((width, height), Image.Resampling.LANCZOS).save(output, "WEBP", quality=82, method=6)
            identifier = f"{name}{width}"
            imports.append(f'import {identifier} from "../../assets/images/{output.name}";')
            candidates.append("${" + identifier + "} " + str(width) + "w")
            sizes.append(output.stat().st_size)
        entries.append(f'  {name}: `'+", ".join(candidates)+'`,')
        original_bytes += source.stat().st_size
        small_bytes += sizes[0]
        large_bytes += sizes[-1]
        print(f"{name}: original={source.stat().st_size}, variants={sizes}")
manifest = "// Generated by scripts/images/generate_variants.py; keep original JPG fallbacks.\n" + "\n".join(imports)
manifest += "\n\nexport const bundledImageSources = {\n" + "\n".join(entries) + "\n};\n"
(ROOT / "shared/utils/bundledImageSources.ts").write_text(manifest, encoding="utf-8", newline="\n")
print(f"Totals: original={original_bytes}, full-width WebP={large_bytes}, small WebP={small_bytes}")
